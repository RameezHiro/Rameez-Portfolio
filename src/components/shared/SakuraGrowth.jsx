// Sakura Growth System — the portfolio's visual metaphor for growth.
//
// One parametric ink illustration, ten hand-composed stages:
//   0 PROLOGUE · 1 CHAPTER 01 · 2 CHAPTER 02 · 3 CHAPTER 03 · 4 CHAPTER 04
//   5 CHAPTER 05 · 6 CHAPTER 06 · 7 CHAPTER 07 · 8 CHAPTER 08 · 9 FINAL
